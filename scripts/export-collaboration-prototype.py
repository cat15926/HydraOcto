#!/usr/bin/env python3
"""Package the local review prototype as one offline HTML file."""

from pathlib import Path
import re


def main() -> None:
    root = Path(__file__).resolve().parents[1] / "prototypes" / "continuous-collaboration"
    html = (root / "index.html").read_text(encoding="utf-8")
    css = (root / "styles.css").read_text(encoding="utf-8")
    javascript = (root / "app.js").read_text(encoding="utf-8")
    settings = (root / "settings.js").read_text(encoding="utf-8")
    stylesheet = '<link rel="stylesheet" href="styles.css">'
    script = '<script src="app.js"></script>'
    if html.count(stylesheet) != 1 or html.count(script) != 1:
        raise SystemExit("Expected exactly one local stylesheet and script in index.html")
    css = re.sub(r"</style", lambda _: r"<\/style", css, flags=re.IGNORECASE)
    javascript = re.sub(r"</script", lambda _: r"<\/script", javascript, flags=re.IGNORECASE)
    html = html.replace(stylesheet, f"<style>\n{css}\n</style>")
    html = html.replace(script, f"<script>\n{javascript}\n</script>")
    settings = re.sub(r"</script", lambda _: r"<\/script", settings, flags=re.IGNORECASE)
    html = html.replace('<script src="settings.js"></script>', f"<script>\n{settings}\n</script>")
    html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/export-collaboration-prototype.py -->", 1)
    destination = root / "prototype.html"
    destination.write_text(html, encoding="utf-8")
    print(destination)


if __name__ == "__main__":
    main()
